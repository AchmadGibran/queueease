-- QueueEase – skema database (Supabase > SQL Editor > New query > Run)
-- Aman dijalankan berulang kali. Jika masih ada tabel `antrean` versi lama, hapus dulu:
--   DROP TABLE IF EXISTS public.antrean CASCADE;

-- 1. Akun pengguna (role: mahasiswa | petugas)
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role VARCHAR(12) NOT NULL CHECK (role IN ('mahasiswa', 'petugas')),
    nim VARCHAR(20) UNIQUE,            -- identitas unik mahasiswa
    username VARCHAR(30) UNIQUE,       -- login petugas
    nama VARCHAR(100) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_identitas_sesuai_role CHECK (
        (role = 'mahasiswa' AND nim IS NOT NULL AND username IS NULL) OR
        (role = 'petugas' AND username IS NOT NULL AND nim IS NULL)
    )
);

-- 2. Jenis layanan: setiap layanan punya kode, penghitung nomor, dan antreannya sendiri
CREATE TABLE IF NOT EXISTS public.layanan (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode VARCHAR(5) NOT NULL UNIQUE,
    nama VARCHAR(100) NOT NULL,
    deskripsi VARCHAR(200) NOT NULL DEFAULT '',
    ikon VARCHAR(20) NOT NULL DEFAULT 'lainnya',
    estimasi_menit SMALLINT NOT NULL DEFAULT 10 CHECK (estimasi_menit > 0),
    batas_harian SMALLINT NOT NULL DEFAULT 100 CHECK (batas_harian > 0),          -- kuota nomor per hari
    maks_per_mahasiswa SMALLINT NOT NULL DEFAULT 1 CHECK (maks_per_mahasiswa > 0), -- maks tiket / mahasiswa / hari
    aktif BOOLEAN NOT NULL DEFAULT TRUE
);

